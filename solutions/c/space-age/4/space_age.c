#include "space_age.h"

float age(planet_t planet, int64_t seconds) {
  const float scale[] = {
      (0.2408467 / 1.0) * 31557600, (0.61519726 / 1.0) * 31557600,
      (1.0 / 1.0) * 31557600,       (1.8808158 / 1.0) * 31557600,
      (11.862615 / 1.0) * 31557600, (29.447498 / 1.0) * 31557600,
      (84.016846 / 1.0) * 31557600, (164.79132 / 1.0) * 31557600};
  return (float)seconds / scale[planet];
}
